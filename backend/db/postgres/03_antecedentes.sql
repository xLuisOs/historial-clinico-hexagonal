SET search_path = hospital01;

CREATE TABLE IF NOT EXISTS antecedente (
  id_antecedente  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  paciente_fk     integer      NOT NULL REFERENCES paciente (id_paciente) ON DELETE RESTRICT,
  tipo            varchar(12)  NOT NULL,
  descripcion     varchar(300) NOT NULL,               -- confidencial
  anio_inicio     smallint,                            -- año aproximado
  registrado_por  integer      NOT NULL REFERENCES medico (id_medico) ON DELETE RESTRICT,
  fecha_registro  timestamp    NOT NULL DEFAULT localtimestamp,
  CONSTRAINT chk_antecedente_tipo CHECK (tipo IN ('patologico', 'quirurgico', 'familiar', 'habito', 'medicamento')),
  CONSTRAINT chk_antecedente_anio CHECK (anio_inicio BETWEEN 1900 AND 2100)
);
CREATE INDEX IF NOT EXISTS idx_antecedente_paciente ON antecedente (paciente_fk);

-- No se registran antecedentes en un historial archivado.
DROP TRIGGER IF EXISTS trg_antecedente_paciente_activo ON antecedente;
CREATE TRIGGER trg_antecedente_paciente_activo BEFORE INSERT ON antecedente
  FOR EACH ROW EXECUTE FUNCTION fn_validar_paciente_activo();

-- Misma seguridad que las demás tablas: RLS, sin acceso para la API de
-- Supabase y hospital_app solo puede leer, insertar y actualizar.
ALTER TABLE antecedente ENABLE ROW LEVEL SECURITY;
DO $$
DECLARE r text;
BEGIN
  FOR r IN SELECT rolname FROM pg_roles WHERE rolname IN ('anon', 'authenticated') LOOP
    EXECUTE format('REVOKE ALL ON hospital01.antecedente FROM %I', r);
  END LOOP;
END $$;
GRANT SELECT, INSERT, UPDATE ON antecedente TO hospital_app;
DROP POLICY IF EXISTS backend_hospital ON antecedente;
CREATE POLICY backend_hospital ON antecedente FOR ALL TO hospital_app USING (true) WITH CHECK (true);

