-- RLS en todas las tablas: aunque alguien llegara a ellas por la API de
-- Supabase, sin una política que lo permita no ve ni modifica nada.
DO $$
DECLARE t text;
BEGIN
  FOR t IN SELECT tablename FROM pg_tables WHERE schemaname = 'hospital01' LOOP
    EXECUTE format('ALTER TABLE hospital01.%I ENABLE ROW LEVEL SECURITY', t);
  END LOOP;
END $$;

-- Los roles de la API de Supabase no tienen acceso al esquema.
DO $$
DECLARE r text;
BEGIN
  FOR r IN SELECT rolname FROM pg_roles WHERE rolname IN ('anon', 'authenticated') LOOP
    EXECUTE format('REVOKE ALL ON SCHEMA hospital01 FROM %I', r);
    EXECUTE format('REVOKE ALL ON ALL TABLES IN SCHEMA hospital01 FROM %I', r);
  END LOOP;
END $$;

-- Usuario con el que se conecta el backend: puede leer, insertar y actualizar,
-- pero NO borrar ni alterar estructura. Así, aunque alguien comprometa la
-- aplicación, no puede eliminar historiales clínicos.
-- ⚠ Cambia la contraseña antes de ejecutar.
CREATE ROLE hospital_app LOGIN PASSWORD 'CAMBIA_ESTA_CLAVE';
ALTER ROLE hospital_app SET search_path = hospital01;
ALTER ROLE hospital_app SET timezone = 'America/Guatemala';

GRANT USAGE ON SCHEMA hospital01 TO hospital_app;
GRANT SELECT, INSERT, UPDATE ON ALL TABLES IN SCHEMA hospital01 TO hospital_app;
GRANT USAGE ON ALL SEQUENCES IN SCHEMA hospital01 TO hospital_app;

-- Con RLS activo, hospital_app solo entra a las tablas por esta política.
DO $$
DECLARE t text;
BEGIN
  FOR t IN SELECT tablename FROM pg_tables WHERE schemaname = 'hospital01' LOOP
    EXECUTE format(
      'CREATE POLICY backend_hospital ON hospital01.%I FOR ALL TO hospital_app USING (true) WITH CHECK (true)', t);
  END LOOP;
END $$;
