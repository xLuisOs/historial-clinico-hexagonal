-- =====================================================================
-- Hospital General — PostgreSQL (Supabase)
-- Esquema relacional corregido (Entrega II)
--
-- Cambios respecto a la Entrega I:
--   * DIAGNOSTICO pasa a ser una tabla (N diagnósticos por consulta, CIE-10),
--     en lugar de un varchar dentro de CONSULTA.
--   * USUARIO para autenticación y enrutamiento por institución.
--   * detalle_receta: duracion (texto) -> duracion_dias (número), + via e indicaciones.
--   * receta: + indicaciones generales.  paciente: + detalle_baja y alergias.
--   * ANTECEDENTE: antecedentes médicos del paciente (patológicos, quirúrgicos,
--     familiares, hábitos y medicamentos).
--   * Restricciones NOT NULL / CHECK / UNIQUE explícitas y triggers para las
--     reglas que involucran varias tablas.
--   * Todas las FK con ON DELETE RESTRICT: un historial nunca se borra, se archiva.
--
-- Las tablas viven en el esquema "hospital01" (no en "public") para que la API
-- automática de Supabase no las exponga.
-- =====================================================================

SET timezone = 'America/Guatemala';

CREATE SCHEMA hospital01;
SET search_path = hospital01;

-- ---------------------------------------------------------------------
-- Personas
-- ---------------------------------------------------------------------
CREATE TABLE paciente (
  id_paciente       integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombres           varchar(100) NOT NULL,
  apellidos         varchar(100) NOT NULL,
  fecha_nacimiento  date         NOT NULL,
  sexo              char(1)      NOT NULL,
  dpi               char(13),                          -- restringido
  telefono          varchar(20),                       -- confidencial
  direccion         varchar(200),                      -- confidencial
  correo            varchar(120),                      -- confidencial
  tipo_sangre       varchar(3),                        -- confidencial
  alergias          varchar(500),                      -- confidencial
  fecha_registro    timestamp    NOT NULL DEFAULT localtimestamp,
  estado            varchar(10)  NOT NULL DEFAULT 'activo',
  fecha_baja        timestamp,                         -- confidencial
  motivo_baja       varchar(20),                       -- confidencial
  detalle_baja      varchar(300),                      -- confidencial
  CONSTRAINT uq_paciente_dpi UNIQUE (dpi),
  CONSTRAINT chk_paciente_sexo CHECK (sexo IN ('M', 'F')),
  CONSTRAINT chk_paciente_dpi CHECK (dpi ~ '^[0-9]{13}$'),
  CONSTRAINT chk_paciente_sangre CHECK (tipo_sangre IN ('A+','A-','B+','B-','AB+','AB-','O+','O-')),
  CONSTRAINT chk_paciente_estado CHECK (estado IN ('activo', 'archivado')),
  CONSTRAINT chk_paciente_motivo_baja CHECK (motivo_baja IN
    ('traslado', 'fallecimiento', 'mayoria_edad', 'administrativo', 'otro')),
  -- Un paciente activo no tiene datos de baja; uno archivado debe tenerlos.
  CONSTRAINT chk_paciente_baja CHECK (
    (estado = 'activo'    AND fecha_baja IS NULL     AND motivo_baja IS NULL) OR
    (estado = 'archivado' AND fecha_baja IS NOT NULL AND motivo_baja IS NOT NULL))
);
CREATE INDEX idx_paciente_nombre ON paciente (apellidos, nombres);

CREATE TABLE responsable (
  id_responsable  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombres         varchar(100) NOT NULL,
  apellidos       varchar(100) NOT NULL,
  dpi             char(13),                            -- restringido
  telefono        varchar(20),                         -- confidencial
  direccion       varchar(200),                        -- confidencial
  CONSTRAINT uq_responsable_dpi UNIQUE (dpi),
  CONSTRAINT chk_responsable_dpi CHECK (dpi ~ '^[0-9]{13}$')
);

-- Historial de quién ha sido responsable del paciente en cada momento.
CREATE TABLE paciente_responsable (
  id_asignacion   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  paciente_fk     integer     NOT NULL REFERENCES paciente (id_paciente) ON DELETE RESTRICT,
  responsable_fk  integer     NOT NULL REFERENCES responsable (id_responsable) ON DELETE RESTRICT,
  parentesco      varchar(20) NOT NULL,
  es_principal    boolean     NOT NULL DEFAULT false,
  fecha_inicio    timestamp   NOT NULL DEFAULT localtimestamp,
  fecha_fin       timestamp,
  CONSTRAINT chk_paciente_responsable_parentesco CHECK (parentesco IN
    ('madre','padre','abuela','abuelo','tia','tio','hermana','hermano','conyuge','hija','hijo','tutor_legal','otro')),
  CONSTRAINT chk_paciente_responsable_fechas CHECK (fecha_fin IS NULL OR fecha_fin >= fecha_inicio)
);
-- Un solo responsable principal vigente por paciente.
CREATE UNIQUE INDEX uq_responsable_principal_vigente
  ON paciente_responsable (paciente_fk) WHERE es_principal AND fecha_fin IS NULL;

-- ---------------------------------------------------------------------
-- Personal y estructura del hospital
-- ---------------------------------------------------------------------
CREATE TABLE especialidad (
  id_especialidad  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre           varchar(80) NOT NULL,
  CONSTRAINT uq_especialidad_nombre UNIQUE (nombre)
);

CREATE TABLE departamento (
  id_departamento  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre           varchar(80)  NOT NULL,
  ubicacion        varchar(120),
  CONSTRAINT uq_departamento_nombre UNIQUE (nombre)
);

CREATE TABLE medico (
  id_medico         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombres           varchar(100) NOT NULL,
  apellidos         varchar(100) NOT NULL,
  numero_colegiado  varchar(10)  NOT NULL,
  especialidad_fk   integer REFERENCES especialidad (id_especialidad) ON DELETE RESTRICT,
  departamento_fk   integer REFERENCES departamento (id_departamento) ON DELETE RESTRICT,
  telefono          varchar(20),                       -- confidencial
  correo            varchar(120),                      -- confidencial
  estado            varchar(10)  NOT NULL DEFAULT 'activo',
  CONSTRAINT uq_medico_colegiado UNIQUE (numero_colegiado),
  CONSTRAINT chk_medico_estado CHECK (estado IN ('activo', 'inactivo'))
);

CREATE TABLE habitacion (
  id_habitacion    integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  numero           varchar(10) NOT NULL,
  departamento_fk  integer REFERENCES departamento (id_departamento) ON DELETE RESTRICT,
  tipo             varchar(20) NOT NULL,
  estado           varchar(15) NOT NULL DEFAULT 'disponible',
  CONSTRAINT uq_habitacion_numero UNIQUE (numero),
  CONSTRAINT chk_habitacion_tipo CHECK (tipo IN ('individual', 'compartida', 'intensivos')),
  CONSTRAINT chk_habitacion_estado CHECK (estado IN ('disponible', 'ocupada', 'mantenimiento'))
);

-- Credenciales de acceso. La contraseña se guarda como hash bcrypt (60 caracteres).
CREATE TABLE usuario (
  id_usuario      integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  correo          varchar(120) NOT NULL,
  password_hash   char(60)     NOT NULL,               -- restringido
  nombre_mostrar  varchar(120) NOT NULL,
  rol             varchar(10)  NOT NULL,
  medico_fk       integer REFERENCES medico (id_medico) ON DELETE RESTRICT,
  activo          boolean      NOT NULL DEFAULT true,
  ultimo_acceso   timestamp,
  CONSTRAINT uq_usuario_correo UNIQUE (correo),
  CONSTRAINT uq_usuario_medico UNIQUE (medico_fk),
  CONSTRAINT chk_usuario_rol CHECK (rol IN ('medico', 'recepcion', 'admin')),
  CONSTRAINT chk_usuario_medico CHECK (rol <> 'medico' OR medico_fk IS NOT NULL)
);

-- ---------------------------------------------------------------------
-- Atención
-- ---------------------------------------------------------------------
CREATE TABLE cita (
  id_cita     integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  paciente_fk integer     NOT NULL REFERENCES paciente (id_paciente) ON DELETE RESTRICT,
  medico_fk   integer     NOT NULL REFERENCES medico (id_medico) ON DELETE RESTRICT,
  fecha_hora  timestamp   NOT NULL,
  estado      varchar(12) NOT NULL DEFAULT 'programada',
  motivo      varchar(300),                            -- confidencial
  CONSTRAINT chk_cita_estado CHECK (estado IN ('programada', 'confirmada', 'atendida', 'cancelada', 'no_asistio'))
);
CREATE INDEX idx_cita_medico_fecha ON cita (medico_fk, fecha_hora);
CREATE INDEX idx_cita_paciente ON cita (paciente_fk);

-- La cita es opcional: las emergencias se atienden sin cita previa.
CREATE TABLE consulta (
  id_consulta          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cita_fk              integer REFERENCES cita (id_cita) ON DELETE RESTRICT,
  paciente_fk          integer   NOT NULL REFERENCES paciente (id_paciente) ON DELETE RESTRICT,
  medico_fk            integer   NOT NULL REFERENCES medico (id_medico) ON DELETE RESTRICT,
  fecha_hora_atencion  timestamp NOT NULL DEFAULT localtimestamp,
  motivo_consulta      varchar(300),                   -- confidencial
  es_emergencia        boolean   NOT NULL DEFAULT false,
  CONSTRAINT uq_consulta_cita UNIQUE (cita_fk)
);
CREATE INDEX idx_consulta_paciente ON consulta (paciente_fk, fecha_hora_atencion);

CREATE TABLE diagnostico (
  id_diagnostico  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  consulta_fk     integer      NOT NULL REFERENCES consulta (id_consulta) ON DELETE RESTRICT,
  codigo_cie10    varchar(10),                         -- restringido
  descripcion     varchar(300) NOT NULL,               -- restringido
  tipo            varchar(10)  NOT NULL DEFAULT 'principal',
  CONSTRAINT chk_diagnostico_tipo CHECK (tipo IN ('principal', 'secundario')),
  CONSTRAINT chk_diagnostico_cie10 CHECK (codigo_cie10 ~ '^[A-Z][0-9]{2}(\.[0-9A-Z]{1,4})?$')
);
-- Una consulta tiene un solo diagnóstico principal.
CREATE UNIQUE INDEX uq_diagnostico_principal ON diagnostico (consulta_fk) WHERE tipo = 'principal';
CREATE INDEX idx_diagnostico_consulta ON diagnostico (consulta_fk);

-- Antecedentes médicos del paciente: lo que no sale de una consulta en
-- particular (enfermedades de base, cirugías previas, antecedentes familiares,
-- hábitos y medicamentos que toma). Los registra un médico; nunca se borran.
CREATE TABLE antecedente (
  id_antecedente  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  paciente_fk     integer      NOT NULL REFERENCES paciente (id_paciente) ON DELETE RESTRICT,
  tipo            varchar(12)  NOT NULL,
  descripcion     varchar(300) NOT NULL,               -- confidencial
  anio_inicio     smallint,                            -- año aproximado
  registrado_por  integer      NOT NULL REFERENCES medico (id_medico) ON DELETE RESTRICT,
  fecha_registro  timestamp    NOT NULL DEFAULT localtimestamp,
  CONSTRAINT chk_antecedente_tipo CHECK (tipo IN ('patologico', 'quirurgico', 'familiar', 'habito', 'medicamento')),
  CONSTRAINT chk_antecedente_anio CHECK (anio_inicio BETWEEN 1900 AND 2100)
);
CREATE INDEX idx_antecedente_paciente ON antecedente (paciente_fk);

CREATE TABLE internamiento (
  id_internamiento       integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  paciente_fk            integer     NOT NULL REFERENCES paciente (id_paciente) ON DELETE RESTRICT,
  habitacion_fk          integer     NOT NULL REFERENCES habitacion (id_habitacion) ON DELETE RESTRICT,
  medico_responsable_fk  integer     NOT NULL REFERENCES medico (id_medico) ON DELETE RESTRICT,
  fecha_ingreso          timestamp   NOT NULL DEFAULT localtimestamp,
  fecha_alta             timestamp,
  motivo_ingreso         varchar(300),                 -- confidencial
  diagnostico_ingreso    varchar(300),                 -- restringido
  diagnostico_alta       varchar(300),                 -- restringido
  estado                 varchar(10) NOT NULL DEFAULT 'activo',
  CONSTRAINT chk_internamiento_estado CHECK (estado IN ('activo', 'alta')),
  CONSTRAINT chk_internamiento_alta CHECK (
    (estado = 'activo' AND fecha_alta IS NULL) OR
    (estado = 'alta'   AND fecha_alta IS NOT NULL AND fecha_alta >= fecha_ingreso))
);
-- Una habitación no puede tener dos internamientos activos.
CREATE UNIQUE INDEX uq_habitacion_ocupada ON internamiento (habitacion_fk) WHERE estado = 'activo';
CREATE INDEX idx_internamiento_paciente ON internamiento (paciente_fk);

-- Historial de qué médico ha estado a cargo durante la estadía.
CREATE TABLE internamiento_medico (
  id_asignacion     integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  internamiento_fk  integer   NOT NULL REFERENCES internamiento (id_internamiento) ON DELETE RESTRICT,
  medico_fk         integer   NOT NULL REFERENCES medico (id_medico) ON DELETE RESTRICT,
  fecha_inicio      timestamp NOT NULL DEFAULT localtimestamp,
  fecha_fin         timestamp,
  motivo_cambio     varchar(300),
  CONSTRAINT chk_internamiento_medico_fechas CHECK (fecha_fin IS NULL OR fecha_fin >= fecha_inicio)
);

-- Un tratamiento, una receta o una factura vienen de una consulta O de un internamiento.
CREATE TABLE tratamiento (
  id_tratamiento    integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  consulta_fk       integer REFERENCES consulta (id_consulta) ON DELETE RESTRICT,
  internamiento_fk  integer REFERENCES internamiento (id_internamiento) ON DELETE RESTRICT,
  descripcion       varchar(300) NOT NULL,             -- restringido
  fecha_inicio      date         NOT NULL DEFAULT current_date,
  fecha_fin         date,
  indicaciones      varchar(500),                      -- restringido
  CONSTRAINT chk_tratamiento_origen CHECK (num_nonnulls(consulta_fk, internamiento_fk) = 1),
  CONSTRAINT chk_tratamiento_fechas CHECK (fecha_fin IS NULL OR fecha_fin >= fecha_inicio)
);

CREATE TABLE medicamento (
  id_medicamento    integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre            varchar(100) NOT NULL,
  presentacion      varchar(100),
  principio_activo  varchar(100),
  CONSTRAINT uq_medicamento UNIQUE (nombre, presentacion)
);

CREATE TABLE receta (
  id_receta         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  consulta_fk       integer REFERENCES consulta (id_consulta) ON DELETE RESTRICT,
  internamiento_fk  integer REFERENCES internamiento (id_internamiento) ON DELETE RESTRICT,
  medico_fk         integer NOT NULL REFERENCES medico (id_medico) ON DELETE RESTRICT,
  fecha_emision     date    NOT NULL DEFAULT current_date,
  indicaciones      varchar(500),                      -- restringido
  CONSTRAINT chk_receta_origen CHECK (num_nonnulls(consulta_fk, internamiento_fk) = 1),
  CONSTRAINT uq_receta_consulta UNIQUE (consulta_fk)
);

CREATE TABLE detalle_receta (
  id_detalle      integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  receta_fk       integer     NOT NULL REFERENCES receta (id_receta) ON DELETE RESTRICT,
  medicamento_fk  integer     NOT NULL REFERENCES medicamento (id_medicamento) ON DELETE RESTRICT,
  dosis           varchar(60) NOT NULL,                -- restringido
  frecuencia      varchar(60) NOT NULL,                -- restringido
  duracion_dias   smallint    NOT NULL,
  via             varchar(15) NOT NULL DEFAULT 'oral',
  indicaciones    varchar(300),                        -- restringido
  CONSTRAINT uq_detalle_receta_medicamento UNIQUE (receta_fk, medicamento_fk),
  CONSTRAINT chk_detalle_receta_duracion CHECK (duracion_dias BETWEEN 1 AND 365),
  CONSTRAINT chk_detalle_receta_via CHECK (via IN
    ('oral','intramuscular','intravenosa','subcutanea','topica','inhalada','oftalmica','otica','nasal','rectal'))
);

-- ---------------------------------------------------------------------
-- Facturación
-- ---------------------------------------------------------------------
CREATE TABLE factura (
  id_factura        integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  paciente_fk       integer       NOT NULL REFERENCES paciente (id_paciente) ON DELETE RESTRICT,
  consulta_fk       integer REFERENCES consulta (id_consulta) ON DELETE RESTRICT,
  internamiento_fk  integer REFERENCES internamiento (id_internamiento) ON DELETE RESTRICT,
  fecha_emision     timestamp     NOT NULL DEFAULT localtimestamp,
  total             numeric(10,2) NOT NULL DEFAULT 0,  -- confidencial; lo mantiene un trigger
  estado            varchar(10)   NOT NULL DEFAULT 'pendiente',
  CONSTRAINT chk_factura_origen CHECK (num_nonnulls(consulta_fk, internamiento_fk) = 1),
  CONSTRAINT chk_factura_estado CHECK (estado IN ('pendiente', 'pagada', 'anulada')),
  CONSTRAINT chk_factura_total CHECK (total >= 0)
);

CREATE TABLE detalle_factura (
  id_detalle_factura  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  factura_fk          integer       NOT NULL REFERENCES factura (id_factura) ON DELETE RESTRICT,
  descripcion         varchar(200)  NOT NULL,
  cantidad            smallint      NOT NULL DEFAULT 1,
  precio_unitario     numeric(10,2) NOT NULL,
  -- Columna generada: el subtotal nunca puede quedar inconsistente.
  subtotal            numeric(10,2) GENERATED ALWAYS AS (cantidad * precio_unitario) STORED,
  CONSTRAINT chk_detalle_factura_cantidad CHECK (cantidad > 0),
  CONSTRAINT chk_detalle_factura_precio CHECK (precio_unitario >= 0)
);

CREATE TABLE pago (
  id_pago      integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  factura_fk   integer       NOT NULL REFERENCES factura (id_factura) ON DELETE RESTRICT,
  fecha_pago   timestamp     NOT NULL DEFAULT localtimestamp,
  monto        numeric(10,2) NOT NULL,                 -- confidencial
  metodo_pago  varchar(15)   NOT NULL,
  referencia   varchar(40),                            -- confidencial
  CONSTRAINT chk_pago_monto CHECK (monto > 0),
  CONSTRAINT chk_pago_metodo CHECK (metodo_pago IN ('efectivo', 'tarjeta', 'transferencia', 'seguro'))
);

-- ---------------------------------------------------------------------
-- Reglas que un CHECK no puede expresar porque involucran otras tablas.
-- La aplicación también las valida, pero la base es la última línea de defensa.
-- ---------------------------------------------------------------------

-- No se agendan ni registran atenciones para un historial archivado.
CREATE FUNCTION fn_validar_paciente_activo() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF (SELECT estado FROM hospital01.paciente WHERE id_paciente = NEW.paciente_fk) = 'archivado' THEN
    RAISE EXCEPTION 'El historial del paciente está archivado' USING ERRCODE = 'P0001';
  END IF;
  RETURN NEW;
END $$;

-- La consulta debe ser del mismo paciente que su cita.
CREATE FUNCTION fn_validar_consulta() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF NEW.cita_fk IS NOT NULL
     AND NEW.paciente_fk <> (SELECT paciente_fk FROM hospital01.cita WHERE id_cita = NEW.cita_fk) THEN
    RAISE EXCEPTION 'La cita no pertenece al paciente' USING ERRCODE = 'P0001';
  END IF;
  RETURN NEW;
END $$;

CREATE TRIGGER trg_cita_paciente_activo BEFORE INSERT ON cita
  FOR EACH ROW EXECUTE FUNCTION fn_validar_paciente_activo();
CREATE TRIGGER trg_consulta_paciente_activo BEFORE INSERT ON consulta
  FOR EACH ROW EXECUTE FUNCTION fn_validar_paciente_activo();
CREATE TRIGGER trg_consulta_cita_del_paciente BEFORE INSERT ON consulta
  FOR EACH ROW EXECUTE FUNCTION fn_validar_consulta();
CREATE TRIGGER trg_antecedente_paciente_activo BEFORE INSERT ON antecedente
  FOR EACH ROW EXECUTE FUNCTION fn_validar_paciente_activo();
CREATE TRIGGER trg_internamiento_paciente_activo BEFORE INSERT ON internamiento
  FOR EACH ROW EXECUTE FUNCTION fn_validar_paciente_activo();

-- El total de la factura es siempre la suma de su detalle.
CREATE FUNCTION fn_recalcular_total_factura() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  UPDATE hospital01.factura f
  SET total = COALESCE((SELECT SUM(subtotal) FROM hospital01.detalle_factura WHERE factura_fk = f.id_factura), 0)
  WHERE f.id_factura = COALESCE(NEW.factura_fk, OLD.factura_fk);
  RETURN NULL;
END $$;

CREATE TRIGGER trg_detalle_factura_total AFTER INSERT OR UPDATE OR DELETE ON detalle_factura
  FOR EACH ROW EXECUTE FUNCTION fn_recalcular_total_factura();

-- Un pago no puede exceder el saldo ni aplicarse a una factura cerrada; al
-- completar el monto, la factura pasa a 'pagada'.
CREATE FUNCTION fn_validar_pago() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
  v_estado varchar;
  v_saldo  numeric;
BEGIN
  SELECT f.estado, f.total - COALESCE((SELECT SUM(monto) FROM hospital01.pago WHERE factura_fk = f.id_factura), 0)
  INTO v_estado, v_saldo
  FROM hospital01.factura f WHERE f.id_factura = NEW.factura_fk
  FOR UPDATE;

  IF v_estado <> 'pendiente' THEN
    RAISE EXCEPTION 'La factura no está pendiente' USING ERRCODE = 'P0001';
  END IF;
  IF NEW.monto > v_saldo THEN
    RAISE EXCEPTION 'El pago excede el saldo de la factura' USING ERRCODE = 'P0001';
  END IF;
  IF NEW.monto = v_saldo THEN
    UPDATE hospital01.factura SET estado = 'pagada' WHERE id_factura = NEW.factura_fk;
  END IF;
  RETURN NEW;
END $$;

CREATE TRIGGER trg_pago_validar BEFORE INSERT ON pago
  FOR EACH ROW EXECUTE FUNCTION fn_validar_pago();

