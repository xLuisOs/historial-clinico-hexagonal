-- =====================================================================
-- Hospital General — agrega RECEPCIONISTA a una base que ya existe.
--
-- Solo hace falta si la base se creó antes de que 01_esquema.sql trajera la
-- tabla recepcionista. Se pega completo en el SQL Editor de Supabase. No borra
-- nada y se puede correr más de una vez.
--
-- Las cuentas de recepción que ya existen siguen funcionando: a cada una se le
-- crea su recepcionista a partir de nombre_mostrar ("Recepción" queda como
-- "Recepción General"). Después el admin corrige los nombres desde el sistema.
-- =====================================================================

SET search_path = hospital01;

CREATE TABLE IF NOT EXISTS recepcionista (
  id_recepcionista  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombres           varchar(100) NOT NULL,
  apellidos         varchar(100) NOT NULL,
  telefono          varchar(20),                       -- confidencial
  estado            varchar(10)  NOT NULL DEFAULT 'activo',
  fecha_registro    timestamp    NOT NULL DEFAULT localtimestamp,
  CONSTRAINT chk_recepcionista_estado CHECK (estado IN ('activo', 'inactivo'))
);

ALTER TABLE usuario ADD COLUMN IF NOT EXISTS
  recepcionista_fk integer REFERENCES recepcionista (id_recepcionista) ON DELETE RESTRICT;

-- Una recepcionista por cada cuenta de recepción que todavía no la tenga.
DO $$
DECLARE u record; nuevo integer;
BEGIN
  FOR u IN SELECT id_usuario, nombre_mostrar, activo FROM usuario
           WHERE rol = 'recepcion' AND recepcionista_fk IS NULL LOOP
    INSERT INTO recepcionista (nombres, apellidos, estado)
    VALUES (
      CASE WHEN position(' ' IN trim(u.nombre_mostrar)) > 0
           THEN split_part(trim(u.nombre_mostrar), ' ', 1) ELSE trim(u.nombre_mostrar) END,
      CASE WHEN position(' ' IN trim(u.nombre_mostrar)) > 0
           THEN substr(trim(u.nombre_mostrar), position(' ' IN trim(u.nombre_mostrar)) + 1) ELSE 'General' END,
      CASE WHEN u.activo THEN 'activo' ELSE 'inactivo' END)
    RETURNING id_recepcionista INTO nuevo;
    UPDATE usuario SET recepcionista_fk = nuevo WHERE id_usuario = u.id_usuario;
  END LOOP;
END $$;

-- Las reglas van después de llenar recepcionista_fk.
DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'uq_usuario_recepcionista') THEN
    ALTER TABLE usuario ADD CONSTRAINT uq_usuario_recepcionista UNIQUE (recepcionista_fk);
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'chk_usuario_recepcionista') THEN
    -- Toda cuenta de recepción es de una recepcionista, y solo esas cuentas lo son.
    ALTER TABLE usuario ADD CONSTRAINT chk_usuario_recepcionista
      CHECK ((rol = 'recepcion') = (recepcionista_fk IS NOT NULL));
  END IF;
END $$;

-- Misma seguridad que las demás tablas: RLS, sin acceso para la API de
-- Supabase y hospital_app solo puede leer, insertar y actualizar.
ALTER TABLE recepcionista ENABLE ROW LEVEL SECURITY;
DO $$
DECLARE r text;
BEGIN
  FOR r IN SELECT rolname FROM pg_roles WHERE rolname IN ('anon', 'authenticated') LOOP
    EXECUTE format('REVOKE ALL ON hospital01.recepcionista FROM %I', r);
  END LOOP;
END $$;
GRANT SELECT, INSERT, UPDATE ON recepcionista TO hospital_app;
DROP POLICY IF EXISTS backend_hospital ON recepcionista;
CREATE POLICY backend_hospital ON recepcionista FOR ALL TO hospital_app USING (true) WITH CHECK (true);
